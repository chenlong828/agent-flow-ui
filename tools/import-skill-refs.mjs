const NAME_LIST = Object.keys(REFS);

async function uploadOne(skill, files, detail, draft) {
  for (const [path, content] of files) {
    const fd = new FormData();
    fd.append('path', path);
    fd.append('file', new Blob([content], { type: 'text/markdown' }), path.split('/').pop());
    const res = await fetch(BASE + '/api/v1/skill-drafts/' + draft.id + '/files', { method: 'POST', body: fd });
    const text = await res.text();
    if (!res.ok) throw new Error('upload ' + skill.name + ' ' + path + ' -> ' + res.status + ' ' + text.slice(0, 200));
  }
  const payload = {
    name: detail.name,
    categoryCode: detail.categoryCode,
    description: detail.description,
    tags: detail.tags || [],
    body: detail.body
  };
  const saved = await call('POST', '/api/v1/skill-drafts/' + draft.id + '/save', payload, { 'If-Match': '"' + draft.baseRevision + '"' });
  return saved;
}

async function main() {
  const skills = await listAll('/api/v1/skills');
  let totalFiles = 0;
  for (const name of NAME_LIST) {
    const skill = skills.find(s => s.name === name);
    if (!skill) throw new Error('找不到 Skill: ' + name);
    const detail = await call('GET', '/api/v1/skills/' + skill.id);
    const draft = await call('POST', '/api/v1/skill-drafts', { skillId: skill.id });
    const saved = await uploadOne(skill, REFS[name], detail, draft);
    totalFiles += REFS[name].length;
    console.log('✓ ' + name + ' +' + REFS[name].length + ' refs → ' + saved.version);
  }
  console.log('\n完成：' + NAME_LIST.length + ' 条 Skill，' + totalFiles + ' 个引用文件');
}

main().catch(err => { console.error('FAIL:', err.message); process.exit(1); });
